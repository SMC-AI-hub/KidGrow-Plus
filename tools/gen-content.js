// Regenerates js/cdata.gen.js from data/*.json (clinician-editable sources).
// Run: node tools/gen-content.js   (from repo root; commit the output)
const fs = require("fs");
const path = require("path");
const R = path.join(__dirname, "..");
const out = {};
for (const f of ["intergrowth.json", "icd10.json", "strings.en.json", "vitals.json", "templates.json", "formulary.json", "labs.json", "nicu.json"]) {
  const name = f.replace(".json", "").replace(".", "_");
  out[name] = JSON.parse(fs.readFileSync(path.join(R, "data", f), "utf8"));
}
const payload = JSON.stringify(out);
const js = "/* GENERATED by tools/gen-content.js — do not edit by hand. Sources: data/*.json */\n"
  + "var KGCONTENT = " + payload + ";\n"
  + 'try { if (typeof window !== "undefined" && window) window.KGCONTENT = KGCONTENT; } catch (e) {}\n';
fs.writeFileSync(path.join(R, "js", "cdata.gen.js"), js);
console.log("cdata.gen.js written (" + js.length + " bytes from " + Object.keys(out).join(", ") + ")");
